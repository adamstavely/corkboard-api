// Copies the layout engines, arrow router and Mermaid readers of the Ultimate Diagram skill
// (github.com/khanhchungoc/ultimate-diagraming-skill, MIT) into one TypeScript module per diagram type.
//
//   node scripts/vendor-diagrams.mjs <skill checkout> src/diagrams/vendor   (corkboard-ui keeps the same files in src/app/features/board/diagrams/vendor)
//
// The skill's files are plain scripts that share globals (TOKENS, and each other's functions), so each type's files
// are wrapped in one factory function that takes TOKENS and returns what Corkboard calls. The code is otherwise
// unchanged: to update it, check out a newer release of the skill and run this again.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const [skill, out] = process.argv.slice(2);
if (!skill || !out) {
  console.error('usage: node scripts/vendor-diagrams.mjs <skill checkout> <out dir>');
  process.exit(1);
}
const read = (p) => readFileSync(join(skill, p), 'utf8');
const version = JSON.parse(read('package.json')).version;
const licence = read('LICENSE').trim();

/** What each type's factory includes, in load order, and what it hands back. */
const TYPES = {
  flowchart: {
    files: ['assets/shell/ortho-router.js', 'assets/types/flowchart/engine.js', 'assets/shell/mermaid-flow.js', 'assets/types/flowchart/mermaid.js'],
    exports: ['layoutDiagram', 'loopSides', 'routeEdgesOrthogonal', 'LE', 'fromMermaid', 'toMermaid'],
  },
};

mkdirSync(out, { recursive: true });
for (const [type, { files, exports }] of Object.entries(TYPES)) {
  const body = files.map((f) => `// ── ${f} ──\n${read(f)}`).join('\n');
  const header = `// @ts-nocheck
/* eslint-disable */
// prettier-ignore
// Generated by scripts/vendor-diagrams.mjs from the Ultimate Diagram skill v${version}: do not edit.
// ${files.join(', ')}
/*
${licence}
*/
`;
  const src = `${header}
/** The skill's ${type} engine, router and Mermaid reader, sharing one TOKENS (its text measurements). */
export function ${type}Engine(TOKENS: unknown): unknown {
${body}
return { ${exports.join(', ')} };
}
`;
  writeFileSync(join(out, `${type}.ts`), src);
  console.log(`wrote ${join(out, `${type}.ts`)} (${src.length} bytes)`);
}
